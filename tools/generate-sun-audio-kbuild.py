#!/usr/bin/env python3
"""Translate the OEM Sun audio registry into a standalone Kbuild."""
import ast
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
AUDIO = ROOT / "device/nothing/FroggerPro-kernel/android_kernel_msm-6.6_nothing_sm7750/vendor/qcom/opensource/audio-kernel"


def literal(node, names):
    if isinstance(node, ast.Constant):
        return node.value
    if isinstance(node, ast.Name):
        return names[node.id]
    if isinstance(node, (ast.List, ast.Tuple)):
        return [literal(x, names) for x in node.elts]
    if isinstance(node, ast.Dict):
        return {literal(k, names): literal(v, names) for k, v in zip(node.keys, node.values)}
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return literal(node.left, names) + literal(node.right, names)
    raise ValueError("Unsupported OEM manifest expression: " + ast.dump(node))


def generate():
    registry_path = AUDIO / "audio_modules.bzl"
    target_path = AUDIO / "build/sun.bzl"
    tree = ast.parse(registry_path.read_text())
    names, registry = {}, {}
    for statement in tree.body:
        if isinstance(statement, ast.Assign) and len(statement.targets) == 1:
            target = statement.targets[0]
            if isinstance(target, ast.Name) and target.id != "audio_modules":
                names[target.id] = literal(statement.value, names)
        if isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Call):
            call = statement.value
            if isinstance(call.func, ast.Attribute) and call.func.attr == "register":
                entry = {kw.arg: literal(kw.value, names) for kw in call.keywords}
                if entry["name"] in registry:
                    raise ValueError("Duplicate audio module " + entry["name"])
                registry[entry["name"]] = entry

    calls = [n for n in ast.walk(ast.parse(target_path.read_text()))
             if isinstance(n, ast.Call) and isinstance(n.func, ast.Name)
             and n.func.id == "define_target_modules"]
    assert len(calls) == 1, "Expected one OEM Sun target definition"
    target = {kw.arg: literal(kw.value, {}) for kw in calls[0].keywords
              if kw.arg in ("target", "modules", "config_options")}
    assert target["target"] == "sun"
    selected = target["modules"]
    assert selected and len(set(selected)) == len(selected)
    options = set(target["config_options"])
    for name in selected:
        option = registry[name].get("config_option")
        if option:
            options.add(option)

    lines = [
        "# Generated by device/nothing/FroggerPro/tools/generate-sun-audio-kbuild.py.",
        "# OEM manifest SHA256: " + hashlib.sha256(registry_path.read_bytes()).hexdigest(),
        "# OEM Sun target SHA256: " + hashlib.sha256(target_path.read_bytes()).hexdigest(),
        "ccflags-y += -I$(AUDIO_ROOT) -I$(AUDIO_ROOT)/include",
        "ccflags-y += -I$(AUDIO_ROOT)/include/uapi/audio -I$(AUDIO_ROOT)/config",
        "ccflags-y += -I$(AUDIO_ROOT)/../mm-drivers/msm_ext_display/include",
        "ccflags-y += " + " ".join("-D" + option + "=1" for option in sorted(options)),
        "",
    ]
    for name in selected:
        entry = registry[name]
        sources = list(entry.get("srcs", []))
        for option, branches in entry.get("conditional_srcs", {}).items():
            enabled = option in options
            if isinstance(branches, list):
                sources.extend(branches if enabled else [])
            else:
                sources.extend(branches.get(enabled, []))
        prefix = entry.get("path") or ""
        sources = [str(Path(prefix) / source) for source in sources]
        assert sources, "Empty selected module: " + name
        assert len(set(sources)) == len(sources), "Duplicate sources: " + name
        for source in sources:
            if not source.endswith(".c") or not (AUDIO / source).is_file():
                raise ValueError("Missing or unsupported audio source: " + source)
        lines += [
            "obj-m += " + name + ".o",
            name + "-y := " + " ".join(source[:-2] + ".o" for source in sources),
            "",
        ]
    output = AUDIO / "Kbuild.sun.generated"
    content = "\n".join(lines)
    if not output.exists() or output.read_text() != content:
        output.write_text(content)
    module_list = ROOT / "device/nothing/FroggerPro/configs/kernel/source-audio-modules.mk"
    module_list.parent.mkdir(parents=True, exist_ok=True)
    make_content = "# Generated from OEM audio-kernel/build/sun.bzl.\nBOARD_VENDOR_KERNEL_MODULES_LOAD += " + " ".join(name + ".ko" for name in selected) + "\n"
    if not module_list.exists() or module_list.read_text() != make_content:
        module_list.write_text(make_content)
    print("PASS: generated", len(selected), "OEM Sun audio modules")
    return selected


if __name__ == "__main__":
    generate()