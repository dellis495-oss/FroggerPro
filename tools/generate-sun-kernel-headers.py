#!/usr/bin/env python3
"""Import OEM public DDK header directories for native Sun driver builds."""
import ast
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
KERNEL = ROOT / "device/nothing/FroggerPro-kernel/android_kernel_msm-6.6_nothing_sm7750"
VENDOR = KERNEL / "vendor/qcom/opensource"
COMMON = [
    "mmrm-driver", "mm-drivers", "mm-drivers/hw_fence",
    "mm-drivers/msm_ext_display", "mm-drivers/sync_fence",
    "securemsm-kernel", "synx-kernel",
]
DRIVERS = {"display-drivers": COMMON, "graphics-kernel": COMMON,
           "video-driver": COMMON + ["video-driver"], "camera-kernel": COMMON + ["camera-kernel"],
           "bt-kernel": ["audio-kernel", "wlan/platform", "bt-kernel"]}


DRIVERS["wlan/qcacld-3.0"] = ["wlan/platform", "dataipa"]
DRIVERS["datarmnet/core"] = ["dataipa", "datarmnet-ext/mem"]
for extension in ["mem", "sch", "aps", "offload", "perf_tether", "shs", "perf", "wlan"]:
    DRIVERS["datarmnet-ext/" + extension] = ["datarmnet", "dataipa", "datarmnet-ext/mem"]


def include_values(node, assignments):
    if isinstance(node, ast.Name):
        return include_values(assignments[node.id], assignments)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return include_values(node.left, assignments) + include_values(node.right, assignments)
    return ast.literal_eval(node)


def generate():
    for driver, dependencies in DRIVERS.items():
        includes = set()
        hashes = []
        for dependency in dependencies:
            source = VENDOR / dependency / "BUILD.bazel"
            tree = ast.parse(source.read_text())
            assignments = {n.targets[0].id: n.value for n in tree.body
                           if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name)}
            hashes.append("# " + dependency + " BUILD.bazel SHA256 " +
                          hashlib.sha256(source.read_bytes()).hexdigest())
            for call in ast.walk(tree):
                if not isinstance(call, ast.Call) or not isinstance(call.func, ast.Name):
                    continue
                if call.func.id != "ddk_headers":
                    continue
                for keyword in call.keywords:
                    if keyword.arg != "includes":
                        continue
                    for directory in include_values(keyword.value, assignments):
                        path = VENDOR / dependency / directory
                        if not path.is_dir():
                            raise ValueError("Missing exported header directory: " + str(path))
                        includes.add(path.relative_to(KERNEL).as_posix())
        content = "\n".join(
            ["# Generated by device/nothing/FroggerPro/tools/generate-sun-kernel-headers.py."]
            + hashes
            + ["subdir-ccflags-y += " +
               " ".join("-I$(KERNEL_SRC)/" + path for path in sorted(includes)), ""]
        )
        output = VENDOR / driver / "Kbuild.lineage_headers"
        if not output.exists() or output.read_text() != content:
            output.write_text(content)
        print("PASS:", driver, len(includes), "OEM exported header directories")


if __name__ == "__main__":
    generate()